export function describeDtc(code) {
  if (DESCRIPTIONS[code]) return DESCRIPTIONS[code];
  const d1 = code[1];
  if (d1 === '1' || d1 === '3') return 'Código específico del fabricante (Renault). Consultar manual de taller.';
  return 'Descripción no disponible en la base local.';
}
