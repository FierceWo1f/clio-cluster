// Decodificación de códigos de falla (DTC) y descripciones en español.

const LETTER = ['P', 'C', 'B', 'U'];

/** Convierte dos bytes (ej. 0x01, 0x71) en un código tipo "P0171". */
export function decodeDtc(b1, b2) {
  const letter = LETTER[b1 >> 6];
  const d1 = (b1 >> 4) & 0x3;
  const rest = ((b1 & 0x0f) << 8 | b2).toString(16).toUpperCase().padStart(3, '0');
  return `${letter}${d1}${rest}`;
}

